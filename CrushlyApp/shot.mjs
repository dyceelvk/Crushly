import { chromium } from '@playwright/test';
const b = await chromium.launch({args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
const p = await b.newPage({viewport:{width:390,height:844}});
p.on('console', m => { const t=m.text(); if(m.type()==='error') console.log('ERR:', t.slice(0,300)); });
p.on('pageerror', e => console.log('PAGEERR:', String(e).slice(0,400)));
await p.goto('http://localhost:8081/', {waitUntil:'load', timeout:120000});
await p.waitForTimeout(8000);
await p.screenshot({path:'/tmp/boot.png'});
console.log((await p.locator('body').innerText()).slice(0,600));
await b.close();
