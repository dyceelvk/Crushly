-- Disposable DB only. Exercises the REAL existing application RPC entry points.
begin;
do $test$
declare a bigint:=7; b bigint:=8; x bigint:=6; au uuid; bu uuid; xu uuid; cv bigint; mid bigint; photo_id bigint; mo bigint; r jsonb; url text; denied boolean;
begin
 select auth_user_id into au from profiles where id=a; select auth_user_id into bu from profiles where id=b; select auth_user_id into xu from profiles where id=x;
 delete from public.blocks where blocker_id in (a,b,x) and blocked_id in (a,b,x);
 delete from public.conversations where (user_a=least(a,b) and user_b=greatest(a,b)) or (user_a=least(a,x) and user_b=greatest(a,x));
 update public.privacy set profile_visibility='everyone',incognito=false,v3_whisper_open=false where user_id in (a,b,x);
 insert into public.moments(user_id,kind,body,audience,created_at,expires_at) values(b,'text','Original moment','everyone',public.now_ms(),public.now_ms()+3600000) returning id into mo;
 perform set_config('request.jwt.claim.sub',au::text,true); set local role authenticated;
 cv:=(public.open_conversation(b)->>'id')::bigint;
 r:=public.load_conversation(cv); assert (r->>'canSend')::boolean and r->>'requestState'='pending';
 assert r#>'{peer,online}'='null'::jsonb, 'pending peer online leaked';
 assert jsonb_array_length(public.v3_whisper_request_list()->'items')=0, 'request leaked to sender inbox';
 assert (public.reply_to_moment(mo,'First request')->>'conversationId')::bigint=cv, 'Moment reply did not use request thread';
 reset role;
 select id into mid from public.messages where conversation_id=cv and kind='moment_reply';
 perform set_config('request.jwt.claim.sub',au::text,true); set local role authenticated;
 url:='messages/'||a||'/v3-request-photo.jpg';
 photo_id:=(public.send_message(cv,'photo','',url,'{}')->>'id')::bigint;
 assert not (public.load_conversation(cv)->>'canSend')::boolean, 'two-message cap not displayed';
 denied:=false; begin perform public.send_message(cv,'text','Third',null,'{}'); exception when sqlstate 'P0001' then denied:=sqlerrm like '__CRUSHLY__403__request_limit%'; end; assert denied, 'third real send succeeded';
 denied:=false; begin perform public.reply_to_moment(mo,'third via Moment'); exception when sqlstate 'P0001' then denied:=sqlerrm like '__CRUSHLY__403__request_limit%'; end; assert denied, 'Moment reply bypassed quota';
 assert public.delete_whisper(photo_id,false), 'sender can hide a request';
 denied:=false; begin perform public.send_message(cv,'text','Third after hide',null,'{}'); exception when sqlstate 'P0001' then denied:=sqlerrm like '__CRUSHLY__403__request_limit%'; end; assert denied, 'deletion bypassed quota';
 assert not public.can_join_whisper('whisper:'||cv), 'unsafe Realtime join enabled';
 reset role;
 perform set_config('request.jwt.claim.sub',bu::text,true); set local role authenticated;
 r:=public.v3_whisper_request_list(); assert jsonb_array_length(r->'items')=1, 'recipient inbox missing request';
 assert r#>'{items,0,peer,online}'='null'::jsonb, 'inbox presence leaked';
 assert (public.load_conversation(cv)->>'isIncomingRequest')::boolean, 'recipient not told request is incoming';
 assert (public.can_view_media(url,url)->>'allowed')::boolean, 'recipient cannot see request photo';
 assert public.whisper_moment_target(mid) is not null, 'recipient cannot open valid target Moment';
 assert jsonb_array_length(public.get_messages(cv)->'items')=2, 'recipient cannot read request';
 r:=public.peer_presence(cv); assert not (r->>'receipts')::boolean and not (r->>'announce')::boolean and r->'online'='null'::jsonb, 'pending presence leaked';
 r:=public.mark_messages_delivered(cv,null); assert (r->>'count')::int=0, 'pending delivery receipt allowed';
 assert public.mark_conversation_read(cv), 'recipient cannot read notification';
 denied:=false; begin perform public.toggle_message_reaction(mid,'laugh'); exception when sqlstate 'P0001' then denied:=true; end; assert denied, 'pending reaction sent';
 denied:=false; begin perform public.register_call_room(cv); exception when sqlstate 'P0001' then denied:=true; end; assert denied, 'pending call allowed';
 reset role;
 assert (select delivered_at is null and read_at is null from public.messages where id=mid), 'pending receipt timestamps leaked';
 perform set_config('request.jwt.claim.sub',xu::text,true); set local role authenticated;
 assert not public.whisper_can_read(mid) and not (public.can_view_media(url,url)->>'allowed')::boolean, 'outsider can read request';
 assert public.whisper_moment_target(mid) is null and jsonb_array_length(public.v3_whisper_request_list()->'items')=0, 'outsider can read target or inbox';
 denied:=false; begin perform public.get_messages(cv); exception when sqlstate 'P0001' then denied:=true; end; assert denied, 'outsider history access';
 reset role;
 perform set_config('request.jwt.claim.sub',bu::text,true); set local role authenticated;
 perform public.send_message(cv,'text','Reply accepts the request',null,'{}');
 assert public.v3_whisper_accepted(cv), 'reply did not accept request';
 assert jsonb_array_length(public.v3_whisper_request_list()->'items')=0, 'accepted request still in inbox';
 assert public.mark_conversation_read(cv); perform public.toggle_message_reaction(mid,'laugh');
 reset role;
 assert (select read_at is not null and delivered_at is not null from public.messages where id=mid), 'accepted receipt missing';
 perform set_config('request.jwt.claim.sub',au::text,true); set local role authenticated;
 perform public.send_message(cv,'text','Message after acceptance',null,'{}');
 perform public.crush_member(b,false,null);
 perform public.v3_keep_subscribe(b);
 assert exists(select 1 from public.keeps where keeper_id=a and kept_id=b), 'Keep Close missing';
 perform public.uncrush_member(b);
 assert exists(select 1 from public.keeps where keeper_id=a and kept_id=b), 'unfollowing removed Keep Close';
 assert jsonb_array_length(public.v3_keep_people('outgoing')->'items')>=1, 'outgoing Keep Close list missing';
 assert jsonb_array_length(public.v3_keep_people('mutual')->'items')=0, 'one-sided Keep incorrectly mutual';
 perform public.v3_keep_unsubscribe(b);
 assert public.v3_whisper_accepted(cv), 'unsubscribing revoked accepted Whisper';
 perform public.send_message(cv,'text','Still independent',null,'{}');
 reset role;
 perform set_config('request.jwt.claim.sub',bu::text,true); set local role authenticated;
 insert into public.blocks(blocker_id,blocked_id) values(b,a);
 assert not public.whisper_thread_allowed(cv) and not public.whisper_can_read(mid), 'blocked pair retains read access';
 assert public.whisper_moment_target(mid) is null and not (public.can_view_media(url,url)->>'allowed')::boolean, 'blocked pair retains Moment/media';
 denied:=false; begin perform public.send_message(cv,'text','blocked',null,'{}'); exception when sqlstate 'P0001' then denied:=true; end; assert denied, 'blocked send allowed';
 denied:=false; begin perform public.mark_conversation_read(cv); exception when sqlstate 'P0001' then denied:=true; end; assert denied, 'blocked receipt allowed';
 assert not exists(select 1 from public.messages where id=mid) and not exists(select 1 from public.conversations where id=cv), 'blocked pair can use direct RLS';
 reset role;
 raise notice 'real Whisper RPC integration tests passed';
end $test$;
rollback;

-- Subscription hub membership, page boundaries, profile privacy and blocks.
begin;
do $test$
declare u uuid; r jsonb;
begin
 delete from public.blocks where blocker_id in (4,5,6,7) and blocked_id in (4,5,6,7);
 delete from public.keeps where keeper_id in (4,5,6,7) and kept_id in (4,5,6,7);
 update public.privacy set profile_visibility='everyone',incognito=false where user_id in (4,5,6,7);
 insert into public.keeps(keeper_id,kept_id) values(4,5),(4,6),(5,4),(7,4);
 select auth_user_id into u from public.profiles where id=4;
 perform set_config('request.jwt.claim.sub',u::text,true); set local role authenticated;
 r:=public.v3_keep_people('outgoing',0,1);
 assert jsonb_array_length(r->'items')=1 and (r->>'hasMore')::boolean, 'outgoing first page';
 assert jsonb_array_length(public.v3_keep_people('outgoing',1,1)->'items')=1, 'outgoing second page';
 assert jsonb_array_length(public.v3_keep_people('incoming')->'items')=2, 'incoming subscription list';
 assert jsonb_array_length(public.v3_keep_people('mutual')->'items')=1, 'mutual subscription list';
 reset role;
 update public.privacy set incognito=true where user_id=7;
 perform set_config('request.jwt.claim.sub',u::text,true); set local role authenticated;
 r:=public.v3_keep_people('incoming');
 assert not exists(select 1 from jsonb_array_elements(r->'items') x where (x->'profile'->>'id')::int=7 and (x->'profile') ? 'bio'), 'hidden profile details in incoming list';
 insert into public.blocks(blocker_id,blocked_id) values(4,5);
 assert not exists(select 1 from jsonb_array_elements(public.v3_keep_people('incoming')->'items') x where (x->'profile'->>'id')::int=5), 'blocked profile in incoming list';
 assert jsonb_array_length(public.v3_keep_people('mutual')->'items')=0, 'blocked profile in mutual list';
 reset role;
 raise notice 'subscription hub privacy and pagination tests passed';
end $test$;
rollback;
