/**
 * Bundles supabase/migrations/*.sql into supabase/setup.sql — one file you can
 * paste straight into the Supabase dashboard's SQL editor, for people setting
 * up a project without the Supabase CLI. Re-run after editing any migration:
 *
 *   npm run bundle:sql
 *
 * The bundle contains schema only. Demo data stays optional (seed.sql).
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = path.join(dir, 'migrations');
const files = (await readdir(migrationsDir)).filter((f) => f.endsWith('.sql')).sort();

const header = `-- Crushly backend setup (generated by \`npm run bundle:sql\` — do not edit by hand).
-- Paste this whole file into the Supabase dashboard's SQL editor (New query →
-- Run) on a fresh project. It contains the schema, security rules and RPCs.
-- Demo data is NOT included; see seed.sql only if you want it locally.

create extension if not exists pgcrypto with schema extensions;

`;

const parts = [];
for (const f of files) {
  const sql = await readFile(path.join(migrationsDir, f), 'utf8');
  parts.push(`-- ================================ ${f}\n\n${sql.trim()}\n`);
}
const out = path.join(dir, 'setup.sql');
await writeFile(out, header + parts.join('\n'), 'utf8');
console.log(`Wrote ${out} from ${files.length} migration(s).`);

// Also split into numbered parts for the dashboard SQL editor — easier to
// paste one migration at a time, and failures are localized. Run in order.
const splitDir = path.join(dir, 'setup');
await (await import('node:fs/promises')).mkdir(splitDir, { recursive: true });
const labels = ['01-schema', '02-functions', '03-storage', '04-extra', '05-extra'];
for (let i = 0; i < files.length; i += 1) {
  const name = labels[i] ?? `${String(i + 1).padStart(2, '0')}-part`;
  const banner = `-- Crushly setup part ${i + 1} of ${files.length} (from ${files[i]}) — generated by npm run bundle:sql.\n-- Run the parts in order in the Supabase SQL editor. Re-running is safe.\n`;
  const head = i === 0 ? header : '';
  await writeFile(path.join(splitDir, `${name}.sql`), banner + head + parts[i].split('\n').slice(2).join('\n'), 'utf8');
  console.log(`Wrote ${splitDir}/${name}.sql`);
}
